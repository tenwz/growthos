import path from "node:path";
import {
  extractClaims,
  extractReceiptTableIds,
  extractSection,
  hasReceiptsTable,
} from "../markdown/citations.js";
import { parseFrontmatter, stringifyFrontmatter } from "../markdown/frontmatter.js";
import type { LoadedRepo } from "../repo/load.js";
import { MemoSchema } from "../schema/memo.js";
import { isoDate } from "../util/dates.js";
import { ensureDir, exists, readText, relativePath, writeText } from "../util/fs.js";

export interface OutputBlock {
  path: string;
  content: string;
}

export function parseFileBlocks(output: string): OutputBlock[] {
  const blocks: OutputBlock[] = [];
  const pattern = /---FILE:\s*(.+?)\s*---\r?\n([\s\S]*?)---END FILE---/g;
  for (const match of output.matchAll(pattern)) {
    const filePath = (match[1] ?? "").trim();
    const content = (match[2] ?? "").trim();
    if (filePath) blocks.push({ path: filePath, content });
  }
  return blocks;
}

export function validateOutputPath(root: string, target: string): string {
  if (path.isAbsolute(target)) {
    throw new Error(`Output path must be relative: ${target}`);
  }
  const normalized = path.normalize(target);
  if (normalized.startsWith("..")) {
    throw new Error(`Output path escapes the repo: ${target}`);
  }
  if (!normalized.startsWith(`growth${path.sep}`) && !normalized.startsWith("growth/")) {
    throw new Error(`Output path must be inside growth/: ${target}`);
  }
  const resolved = path.resolve(root, normalized);
  const growthRoot = path.resolve(root, "growth");
  if (!resolved.startsWith(`${growthRoot}${path.sep}`) && resolved !== growthRoot) {
    throw new Error(`Output path escapes growth/: ${target}`);
  }
  return normalized;
}

function escapeCell(value: string, max = 90): string {
  const cleaned = value.replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
  return cleaned.length > max ? `${cleaned.slice(0, max - 1)}…` : cleaned;
}

export function buildReceiptsTable(repo: LoadedRepo, receiptIds: string[]): string {
  const rows = receiptIds.map((id) => {
    const signal = repo.signalById.get(id);
    if (!signal) {
      return `| ${id} | (missing) | (missing) |`;
    }
    const source =
      signal.data.source.url ??
      (signal.data.evidence && "source_url" in signal.data.evidence
        ? signal.data.evidence.source_url
        : undefined) ??
      "(evidence block)";
    return `| ${id} | "${escapeCell(signal.data.quote)}" | ${escapeCell(source, 120)} |`;
  });
  return [
    "## Receipts",
    "",
    "<!-- generated by growthOS from the claims above; do not edit by hand -->",
    "",
    "| ID | Quote | Source |",
    "| --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

export function ensureMemoReceipts(repo: LoadedRepo, content: string): string {
  const parsed = parseFrontmatter(content);
  if (parsed.data.schema !== "growthos/memo@1") return content;
  const memo = MemoSchema.safeParse(parsed.data);
  if (!memo.success) return content;
  const claims = extractClaims(parsed.body);
  const receiptIds = [...new Set(claims.flatMap((claim) => claim.citations))];
  const sources = new Set(
    receiptIds
      .map((id) => repo.signalById.get(id)?.data.source.kind)
      .filter((kind): kind is NonNullable<typeof kind> => Boolean(kind)),
  );
  const table = buildReceiptsTable(repo, receiptIds);

  let body = parsed.body;
  const existing = extractSection(body, "Receipts");
  if (existing !== null || hasReceiptsTable(body)) {
    const headingIndex = body.search(/^##\s+Receipts\s*$/im);
    if (headingIndex >= 0) {
      const rest = body.slice(headingIndex);
      const nextHeading = rest.slice(1).search(/^##\s+/m);
      const end = nextHeading >= 0 ? headingIndex + 1 + nextHeading : body.length;
      body = `${body.slice(0, headingIndex)}${table}\n${body.slice(end)}`;
    } else {
      body = `${body.trimEnd()}\n\n${table}\n`;
    }
  } else {
    body = `${body.trimEnd()}\n\n${table}\n`;
  }

  const updatedData = {
    ...memo.data,
    claim_count: claims.length,
    receipt_count: receiptIds.length,
    source_diversity: sources.size,
    created_at: memo.data.created_at || new Date().toISOString(),
  };
  return stringifyFrontmatter(updatedData as unknown as Record<string, unknown>, body);
}

export interface ApplyResult {
  written: string[];
  skipped: { path: string; reason: string }[];
}

export function applyOutputs(
  repo: LoadedRepo,
  blocks: OutputBlock[],
  allowedPaths: string[],
): ApplyResult {
  const written: string[] = [];
  const skipped: { path: string; reason: string }[] = [];

  for (const block of blocks) {
    let relative: string;
    try {
      relative = validateOutputPath(repo.root, block.path);
    } catch (error) {
      skipped.push({ path: block.path, reason: (error as Error).message });
      continue;
    }
    if (allowedPaths.length > 0 && !allowedPaths.includes(relative)) {
      skipped.push({
        path: block.path,
        reason: "Path was not declared in the job output contract.",
      });
      continue;
    }
    const target = path.join(repo.root, relative);
    if (exists(target)) {
      try {
        const existing = parseFrontmatter(readText(target));
        if (existing.data.schema === "growthos/memo@1" && existing.data.status === "published") {
          skipped.push({ path: block.path, reason: "Refusing to overwrite a published memo." });
          continue;
        }
      } catch {
        // Fall through and overwrite unparseable drafts only with an explicit apply.
      }
    }
    const content = relative.endsWith(".md")
      ? ensureMemoReceipts(repo, block.content)
      : block.content;
    writeText(target, content);
    written.push(relative);
  }

  return { written, skipped };
}

export function writeRunOutputs(
  runDir: string,
  blocks: OutputBlock[],
): { outputDir: string; files: string[] } {
  const outputDir = path.join(runDir, "output");
  ensureDir(outputDir);
  const files: string[] = [];
  for (const block of blocks) {
    const target = path.join(outputDir, block.path);
    writeText(target, block.content);
    files.push(relativePath(runDir, target));
  }
  return { outputDir, files };
}

export function writeDiff(runDir: string, result: ApplyResult, dryRun: boolean): string {
  const lines = [
    `# Run output — ${isoDate()}`,
    "",
    dryRun ? "Mode: dry run (not applied). Re-run with `--apply` to write." : "Mode: applied.",
    "",
    "## Would write / wrote",
    ...(result.written.length ? result.written.map((file) => `- ${file}`) : ["- (none)"]),
    "",
    "## Skipped",
    ...(result.skipped.length
      ? result.skipped.map((item) => `- ${item.path}: ${item.reason}`)
      : ["- (none)"]),
    "",
  ];
  const content = lines.join("\n");
  writeText(path.join(runDir, "diff.md"), content);
  return content;
}

export function collectReceiptIdsFromBody(body: string): string[] {
  return extractReceiptTableIds(body);
}
